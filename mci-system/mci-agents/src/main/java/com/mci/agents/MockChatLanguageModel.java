package com.mci.agents;

import dev.langchain4j.data.message.AiMessage;
import dev.langchain4j.data.message.ChatMessage;
import dev.langchain4j.data.message.UserMessage;
import dev.langchain4j.model.chat.ChatLanguageModel;
import dev.langchain4j.model.output.Response;

import java.util.List;

/**
 * Built-in Agent Engine for offline testing, demos, and presentations.
 *
 * It allows the MCI system to execute the full orchestration loop:
 *   1. Subtask DAG generation (Planner)
 *   2. Step-by-step agent execution (SimpleAgent)
 *   3. Security policy check and audit logging (ToolGateway)
 *   4. Workspace file generation (FileTool)
 *
 * This ensures the application is always functional and demoable even
 * when offline or when no external Gemini API key is configured.
 */
public class MockChatLanguageModel implements ChatLanguageModel {

    @Override
    public Response<AiMessage> generate(List<ChatMessage> messages) {
        String lastText = "";
        if (messages != null && !messages.isEmpty()) {
            ChatMessage last = messages.get(messages.size() - 1);
            if (last instanceof UserMessage userMessage) {
                lastText = userMessage.singleText();
            } else {
                lastText = last.toString();
            }
        }
        return Response.from(AiMessage.from(generate(lastText)));
    }

    @Override
    public String generate(String userMessage) {
        if (userMessage == null || userMessage.isBlank()) {
            return "Operation completed successfully.";
        }

        String lower = userMessage.toLowerCase();

        // System ping test
        if (userMessage.contains("Say exactly: 'MCI System Online!'") || lower.contains("mci system online")) {
            return "MCI System Online!";
        }

        // Planner prompt handling
        if (userMessage.contains("You are a task planner")) {
            String objective = "General Objective";
            int idx = userMessage.lastIndexOf("Objective: ");
            if (idx != -1) {
                objective = userMessage.substring(idx + "Objective: ".length()).trim();
            }
            return "STEP|DATA_FILE|Analyze objective and prepare workspace for: " + objective + "\n"
                    + "STEP|DATA_FILE|Process structured information and execute data transformations\n"
                    + "STEP|REPORT|Compile findings and generate final report";
        }

        // Report agent handling
        if (userMessage.contains("You are a REPORT agent") || lower.contains("report agent")) {
            return "# Executive Summary & Task Report\n\n"
                    + "### 1. Objective Status\n"
                    + "The requested task was successfully planned, partitioned into subtasks, and completed.\n\n"
                    + "### 2. Execution Summary\n"
                    + "- **Planner**: Created subtask DAG with dependency order.\n"
                    + "- **Agents**: Dispatched tasks according to agent roles.\n"
                    + "- **Security Gateway**: All file and system actions inspected and approved against security policy.\n"
                    + "- **Audit Trail**: Every request logged into SQLite database with timestamp and outcome.\n\n"
                    + "### 3. Conclusion\n"
                    + "All operations passed verification with status: SUCCESS.\n\n"
                    + "*Generated by Multi-Agent Computer Intelligence System (MCI)*";
        }

        // Data / File agent handling
        if (userMessage.contains("You are a DATA_FILE agent") || lower.contains("data_file agent")) {
            return "Data analysis completed successfully. Input parameters processed and verified within the workspace sandbox.";
        }

        // Navigator agent handling
        if (userMessage.contains("You are a NAVIGATOR agent") || lower.contains("navigator agent")) {
            return "Web query executed and information extracted within security boundaries.";
        }

        // Docker agent handling
        if (userMessage.contains("You are a DOCKER agent") || lower.contains("docker agent")) {
            return "Isolated sandbox container executed task successfully with return code 0.";
        }

        return "Agent operation completed successfully: " + userMessage;
    }
}

